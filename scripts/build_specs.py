def to_number(value) -> float:
    """Первое число из ячейки матрицы. «550-600» -> 550, пусто -> 0."""
    match = re.search(r"\d+(?:[.,]\d+)?", str(value))
    return float(match.group().replace(",", ".")) if match else 0.0


def fill(text: str, sku: pd.Series) -> str:
    # в матрице впитываемость записана как «от 500%» — в требованиях перед
    # ней уже стоит «не менее», второе «от» читается как опечатка
    absorbency = re.sub(r"^\s*от\s+", "", str(sku.get("absorbency", "")))
    return text.format(
        density=sku.get("density", ""),
        absorbency=absorbency,
        sizes=sku.get("size", ""),
        composition=sku.get("composition", ""),
    )


def md_table(rows: list[list[str]]) -> str:
    head, *body = rows
    lines = ["| " + " | ".join(head) + " |",
             "|" + "|".join(["---"] * len(head)) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in body]
    return "\n".join(lines) + "\n"


def sku_section(sku: pd.Series, reviews: pd.DataFrame, themes: dict) -> str:
    family = FAMILY_BY_CATEGORY.get(sku["category"], "полотенце")
    kind = KIND_BY_FAMILY[family]
    scope, size_note = kind_slice(reviews, kind,
                                  TOWEL_GROUP_BY_CATEGORY.get(sku["category"], ""))

    out = [f"## {sku['code']} — {sku['category']} {sku['size']}", ""]

    out.append(md_table([
        ["Параметр", "Значение"],
        ["Роль в линейке", str(sku["role"])],
        ["Размер", str(sku["size"])],
        ["Комплектность", str(sku["pack"])],
        ["Цвета", str(sku["colors"])],
        ["Плотность", f"{sku['density']} г/м²"],
        ["Состав", str(sku["composition"])],
        ["Водопоглощение", str(sku["absorbency"])],
        ["Отделка", str(sku["finish"])],
        ["Целевая цена", f"{sku['target_price']} ₽"],
        ["УТП", str(sku["usp"])],
    ]))

    out.append("### Технические требования\n")
    out.append(md_table([["Параметр", "Требование", "Как проверяем"]] +
                        [[row[0], fill(row[1], sku), row[2]] for row in SPEC_ROWS[family]]))

    # доказательная база
    if scope.empty:
        out.append("> Отзывов по этой категории не собрано — "
                   "обоснование требований добавится после запуска `collect_reviews.py`.\n")
    else:
        out.append("### Обоснование: что пишут в отзывах\n")
        out.append(f"База — {len(scope)} отзывов на карточки конкурентов "
                   f"категории «{kind}»{size_note}.\n")

        rows = [["Претензия покупателя", "Упоминаний", "Рейтинг таких отзывов",
                 "Негатив", "Что фиксируем в ТЗ"]]
        for theme, requirement in EVIDENCE_THEMES[family]:
            stat = theme_stats(scope, themes.get("жалобы", {}).get(theme, []))
            if not stat:
                continue
            mentions, rating, negative = fmt_stat(stat)
            rows.append([theme, mentions, rating, negative, fill(requirement, sku)])
        if len(rows) > 1:
            out.append(md_table(rows))

        praise_rows = [["За что хвалят", "Упоминаний", "Рейтинг"]]
        for theme in PRAISE_THEMES[family]:
            stat = theme_stats(scope, themes.get("похвала", {}).get(theme, []))
            if not stat:
                continue
            mentions, rating, _ = fmt_stat(stat)
            praise_rows.append([theme, mentions, rating])
        if len(praise_rows) > 1:
            out.append("### Что выносим в карточку\n")
            out.append("Формулировки ниже — не копирайтинг, а темы, за которые "
                       "покупатели ставят пятёрки. Их стоит закрыть в ТЗ и потом "
                       "прямо назвать в описании и на инфографике.\n")
            out.append(md_table(praise_rows))

    out.append("### Упаковка и маркировка\n")
    out += [f"- {line}" for line in PACKAGING[family]]
    out.append("")

    risks = [text for condition, text in RISK_RULES if condition(family, sku)]
    if risks:
        out.append("### Риски по этой позиции\n")
        out += [f"- {text}" for text in risks]
        out.append("")

    return "\n".join(out)


def build_markdown(matrix: pd.DataFrame, reviews: pd.DataFrame, themes: dict) -> str:
    out = ["# ТЗ поставщику по позициям линейки", ""]
    out.append("Документ собран автоматически из матрицы SKU и отзывов на карточки "
               "конкурентов Wildberries. Каждое требование в разделе «Обоснование» "
               "привязано к числу отзывов, их среднему рейтингу и доле негатива — "
               "это то, из-за чего покупатели снижают оценку в категории.\n")
    if not reviews.empty:
        out.append(f"Всего в базе: **{len(reviews)} отзывов** на "
                   f"**{reviews['product_id'].nunique()} карточек** конкурентов.\n")

    out.append("## Общие требования ко всей линейке\n")
    out.append("Действуют для каждой позиции ниже, в разделах по SKU не повторяются.\n")
    out.append(md_table([["Параметр", "Требование", "Как проверяем"]] + COMMON_REQUIREMENTS))

    out.append("## Приёмка партии — общий регламент\n")
    out += [f"- {line}" for line in ACCEPTANCE]
    out.append("")

    for _, sku in matrix.iterrows():
        out.append(sku_section(sku, reviews, themes))

    return "\n".join(out)


def render_docx(markdown: str, path: Path) -> Path:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt

    from export_docx import DARK, GREY, render_markdown, setup_styles

    doc = Document()
    setup_styles(doc)

    title = doc.add_paragraph("ТЗ поставщику")
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT
    for run in title.runs:
        run.font.size = Pt(22)
        run.font.bold = True
        run.font.color.rgb = DARK

    subtitle = doc.add_paragraph("Требования по каждой позиции линейки, "
                                 "обоснованные отзывами покупателей")
    for run in subtitle.runs:
        run.font.size = Pt(12)
        run.font.color.rgb = GREY
    doc.add_paragraph()

    render_markdown(doc, markdown, skip_first_heading=True)
    return save_document(path, doc.save)


def main() -> None:
    parser = argparse.ArgumentParser(description="ТЗ поставщику по позициям матрицы")
    parser.add_argument("--config", default="config.yaml")
    args = parser.parse_args()

    cfg = load_config(args.config)
    output = cfg.get("output") or {}
    reports_dir = resolve(output.get("reports_dir", "reports"))
    matrix_path = resolve(output.get("matrix_file", "data/sku_matrix.csv"))
    reviews_path = resolve(output.get("reviews_file", "data/reviews.csv"))

    if not matrix_path.exists():
        sys.exit(f"Нет матрицы {matrix_path}. Сначала заполните data/sku_matrix.csv")

    matrix = pd.read_csv(matrix_path)
    if matrix.empty:
        sys.exit("Матрица пустая — нечего описывать")

    reviews = load_reviews(reviews_path)
    if reviews.empty:
        print("Отзывов нет — ТЗ соберётся без раздела с обоснованием. "
              "Запустите scripts/collect_reviews.py, чтобы его наполнить")

    themes = ((cfg.get("reviews") or {}).get("themes") or {})

    markdown = build_markdown(matrix, reviews, themes)
    reports_dir.mkdir(parents=True, exist_ok=True)

    md_path = save_document(reports_dir / "ТЗ_по_позициям.md",
                            lambda p: p.write_text(markdown, encoding="utf-8"))
    print(f"Готово: {md_path}")

    docx_path = render_docx(markdown, reports_dir / "ТЗ_поставщику.docx")
    print(f"Готово: {docx_path}  ({len(matrix)} позиций)")


if __name__ == "__main__":
    main()
