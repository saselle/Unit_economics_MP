def load_reviews(path: Path) -> pd.DataFrame:
    """Отзывы с уже проставленными «вид товара» и «размер»."""
    if not path.exists():
        return pd.DataFrame()

    df = pd.read_csv(path)
    if df.empty:
        return df

    # тот же фильтр, что в analyze_reviews: чужие отзывы отбрасываем
    if "review_nm_id" in df.columns and "product_id" in df.columns:
        foreign = df["review_nm_id"].notna() & (df["review_nm_id"] != df["product_id"])
        df = df[~foreign]
    if "review_id" in df.columns:
        df = df.drop_duplicates(subset="review_id")

    text_cols = [col for col in ("text", "pros", "cons") if col in df.columns]
    combined = (df[text_cols].fillna("").astype(str).agg(" ".join, axis=1).str.lower()
                if text_cols else pd.Series("", index=df.index))

    return df.assign(
        _text=combined,
        _kind=df["product_title"].map(detect_kind),
        _group=df["product_title"].map(towel_group),
        rating=pd.to_numeric(df["rating"], errors="coerce"),
    )


def theme_stats(df: pd.DataFrame, keywords: list[str]) -> dict | None:
    """Сколько отзывов задевают тему, какой у них рейтинг и сколько негатива."""
    if df.empty or not keywords:
        return None

    mask = pd.Series(False, index=df.index)
    for word in keywords:
        mask |= df["_text"].str.contains(re.escape(word), na=False, regex=True)

    hit = df[mask]
    if hit.empty:
        return None

    rated = hit["rating"].dropna()
    return {
        "mentions": len(hit),
        "share": len(hit) / len(df) * 100,
        "rating": rated.mean() if len(rated) else float("nan"),
        "negative": (rated <= NEGATIVE_RATING).mean() * 100 if len(rated) else float("nan"),
    }


def towel_group(title: str) -> str:
    """Назначение полотенца: салфетка, для лица или банное.

    Сначала смотрим на слова — продавцы пишут назначение прямо в названии.
    Если слов нет, судим по ширине: 65 см и больше — банное, до 40 — салфетка.
    """
    text = str(title).lower()
    if any(word in text for word in ("салфет", "кухон")):
        return "салфетки"
    if any(word in text for word in ("для лица", "лицев", "для рук")):
        return "для лица"
    if any(word in text for word in ("банн", "для ванной", "для душа")):
        return "банное"

    match = SIZE_RE.search(text)
    if not match:
        return ""
    width = int(match.group(1))
    if width >= 65:
        return "банное"
    return "для лица" if width >= 45 else "салфетки"


def kind_slice(reviews: pd.DataFrame, kind: str, group: str = "") -> tuple[pd.DataFrame, str]:
    """Отзывы по виду товара и, если их хватает, по назначению полотенца.

    Возвращает срез и пояснение, по чему он сделан — чтобы в документе было
    видно, на какой выборке построены цифры.

    Дробим только полотенца: на банное жалуются «тонкое» в разы чаще, чем на
    салфетку, это разные требования. У ковриков и халатов претензии
    (скольжение, пояс, посадка) общие для категории — дробить выборку значит
    потерять статистику на ровном месте.
    """
    if reviews.empty:
        return reviews, ""

    sub = reviews[reviews["_kind"] == kind]
    if group and kind == "Полотенце":
        grouped = sub[sub["_group"] == group]
        if len(grouped) >= MIN_SLICE:
            return grouped, f", срез «{group}»"
    return sub, ""


def fmt_stat(stat: dict | None) -> tuple[str, str, str]:
    if not stat:
        return "—", "—", "—"
    rating = "—" if pd.isna(stat["rating"]) else f"{stat['rating']:.2f}"
    negative = "—" if pd.isna(stat["negative"]) else f"{stat['negative']:.0f}%"
    return f"{stat['mentions']} ({stat['share']:.1f}%)", rating, negative


